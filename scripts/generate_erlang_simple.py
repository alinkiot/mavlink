#!/usr/bin/env python3
"""
MAVLink Erlang code generator (Simplified version).
Generates Erlang record definitions and message ID constants.
Compatible with Erlang/OTP 24+
"""

import xml.etree.ElementTree as ET
import sys
import os

def generate_enum(enum_elem):
    """Generate Erlang enum constants."""
    name = enum_elem.get('name')
    entries = enum_elem.findall('entry')
    
    lines = [f'%% Enum: {name}']
    
    for entry in entries:
        entry_name = entry.get('name')
        value = entry.get('value')
        # Define as constant macro
        lines.append(f"-define({entry_name.upper()}, {value}).")
    
    lines.append('')
    return '\n'.join(lines)

def generate_message(message_elem):
    """Generate Erlang record for a message."""
    msg_id = message_elem.get('id')
    msg_name = message_elem.get('name')
    description = message_elem.find('description')
    
    lines = [f'%% Message: {msg_name} (ID: {msg_id})']
    if description is not None and description.text:
        # Handle multi-line descriptions
        desc_lines = description.text.strip().split('\n')
        for desc_line in desc_lines:
            lines.append(f'%% {desc_line.strip()}')
    lines.append('')
    
    # Message ID constant
    lines.append(f"-define({msg_name.upper()}_ID, {msg_id}).")
    lines.append('')
    
    # Generate record
    fields = message_elem.findall('field')
    record_fields = []
    
    for field in fields:
        field_name = field.get('name').lower()
        field_type = field.get('type')
        field_units = field.get('units')
        field_desc = field.text if field.text else ''
        
        # Handle Erlang reserved words
        reserved_words = {'end', 'begin', 'after', 'catch', 'case', 'fun', 'if', 'of', 'receive', 'try', 'when'}
        if field_name in reserved_words:
            field_name = field_name + '_'
        
        # Add field without inline comments (Erlang record fields don't support inline comments)
        record_fields.append(f'    {field_name}')
    
    # Record definition
    lines.append(f'-record({msg_name.lower()}, {{')
    lines.append(',\n'.join(record_fields))
    lines.append('}).')
    lines.append('')
    
    return '\n'.join(lines)

def generate_header(xml_file, output_file, module_name):
    """Generate complete Erlang header file."""
    tree = ET.parse(xml_file)
    root = tree.getroot()
    
    # Header
    lines = [
        f'%% Automatically generated by generate_erlang_simple.py',
        f'%% Source: {os.path.basename(xml_file)}',
        f'%% Compatible with Erlang/OTP 24+',
        f'%% Do not edit manually!',
        '',
        f'-ifndef({module_name.upper()}_HRL).',
        f'-define({module_name.upper()}_HRL, true).',
        '',
    ]
    
    # Generate enums
    enums = root.find('enums')
    if enums is not None:
        lines.append('%%====================================================================')
        lines.append('%% Enums (as constants)')
        lines.append('%%====================================================================')
        lines.append('')
        for enum in enums.findall('enum'):
            lines.append(generate_enum(enum))
    
    # Generate messages
    messages = root.find('messages')
    if messages is not None:
        lines.append('%%====================================================================')
        lines.append('%% Messages (as records)')
        lines.append('%%====================================================================')
        lines.append('')
        for message in messages.findall('message'):
            lines.append(generate_message(message))
    
    lines.append('-endif. %% ' + module_name.upper() + '_HRL')
    
    # Write output
    with open(output_file, 'w') as f:
        f.write('\n'.join(lines))
    
    print(f'✓ Generated {output_file}')
    print(f'  - Enums: {len(enums.findall("enum")) if enums is not None else 0}')
    print(f'  - Messages: {len(messages.findall("message")) if messages is not None else 0}')

def main():
    if len(sys.argv) < 4:
        print(f'Usage: {sys.argv[0]} <input.xml> <output.hrl> <module_name>')
        print(f'Example: {sys.argv[0]} common.xml mavlink.hrl mavlink')
        sys.exit(1)
    
    xml_file = sys.argv[1]
    output_file = sys.argv[2]
    module_name = sys.argv[3]
    
    generate_header(xml_file, output_file, module_name)

if __name__ == '__main__':
    main()
